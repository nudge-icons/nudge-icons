// Writes one Chromatic story per icon from @nudge-icons/svg/icons.json.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const listUrl = new URL("../../../packages/svg/icons.json", import.meta.url);
const list = JSON.parse(readFileSync(listUrl, "utf8")) as { name: string; component: string }[];

const stories = list.map(
  (i) => `export const ${i.component}: Story = { args: { name: ${JSON.stringify(i.name)} } };`,
);
const out = new URL("../src/generated/", import.meta.url);
mkdirSync(out, { recursive: true });
writeFileSync(
  new URL("icons.stories.tsx", out),
  `// Generated by apps/storybook/scripts/gen-stories.ts. Do not edit.
import type { Meta, StoryObj } from "@storybook/react-vite";
import { IconMatrix } from "../icon-matrix";

const meta = { title: "Icons", component: IconMatrix } satisfies Meta<typeof IconMatrix>;
export default meta;
type Story = StoryObj<typeof meta>;

${stories.join("\n")}
`,
);
console.log(`Generated ${stories.length} icon stories`);
