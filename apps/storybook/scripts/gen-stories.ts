// Writes one Chromatic story file per icon from @nudge-icons/svg/icons.json.
// Each file imports only the modules of its own icon, so TurboSnap (--only-changed) retakes
// the snapshots of the icons a commit touched rather than of the whole set.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

interface Listed {
  name: string;
  component: string;
  toggle?: unknown;
  variants: { variant: string; id: string; component: string }[];
}

const listUrl = new URL("../../../packages/svg/icons.json", import.meta.url);
const list = JSON.parse(readFileSync(listUrl, "utf8")) as Listed[];

// From src/generated/icons/ to the generated React modules (not the package index) and to the
// sources. The generated modules are not in git, so each story also imports its own sources:
// that puts them in the dependency graph, and a change to icons/bell.svg retakes Icons/Bell.
const ICON_MODULES = "../../../../../packages/react/src/generated/icons";
const SOURCES = "../../../../../icons";

const out = new URL("../src/generated/icons/", import.meta.url);
rmSync(new URL("../src/generated/", import.meta.url), { recursive: true, force: true });
mkdirSync(out, { recursive: true });

for (const icon of list) {
  const imports = icon.variants
    .map((v) => `import { ${v.component} } from "${ICON_MODULES}/${v.id}";`)
    .join("\n");
  const sources = [
    `${SOURCES}/${icon.name}.json`,
    ...icon.variants.map((v) =>
      v.variant === "outline"
        ? `${SOURCES}/${icon.name}.svg`
        : `${SOURCES}/${v.variant}/${icon.name}.svg`,
    ),
  ]
    .map((path) => `import "${path}";`)
    .join("\n");
  const variants = icon.variants
    .map((v) => `{ variant: ${JSON.stringify(v.variant)}, Icon: ${v.component} }`)
    .join(", ");
  writeFileSync(
    new URL(`${icon.name}.stories.tsx`, out),
    `// Generated by apps/storybook/scripts/gen-stories.ts. Do not edit.
import type { Meta, StoryObj } from "@storybook/react-vite";
${imports}
import { IconMatrix } from "../../icon-matrix";
// Sources, for TurboSnap only.
${sources}

const meta = {
  title: "Icons/${icon.component}",
  component: IconMatrix,
  args: { toggle: ${"toggle" in icon}, variants: [${variants}] },
} satisfies Meta<typeof IconMatrix>;
export default meta;

export const Matrix: StoryObj<typeof meta> = {};
`,
  );
}
console.log(`Generated ${list.length} icon stories`);
