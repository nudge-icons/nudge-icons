// Generates the shadcn registry (React) and the shadcn-vue registry from the generated
// package sources, so `npx shadcn add` copies the same code that ships in the npm packages.
// Run after build-icons.ts. Output goes to the site's public folder and is served by Pages.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
// Items point at the shared core by absolute URL.
import { CORE_DIR, CORE_ITEM, ICONS_DIR, VUE_DIR } from "./lib/registry-layout.ts";
import { registryUrl, siteUrl } from "./lib/site-url.ts";

const root = join(import.meta.dirname, "..");
const out = join(root, "apps", "site", "public", "r");

interface Flavor {
  /** Subfolder of r/ for this registry: "" for React, VUE_DIR for Vue. */
  dir: string;
  label: string;
  pkg: string;
  /** npm dependencies the copied code needs; the framework itself is assumed. */
  dependencies: string[];
}

const FLAVORS: Flavor[] = [
  { dir: "", label: "React", pkg: "react", dependencies: [] },
  { dir: VUE_DIR, label: "Vue", pkg: "vue", dependencies: [] },
];

interface IconListEntry {
  name: string;
  category?: string;
  tags?: string[];
  variants: { variant: string; id: string; component: string }[];
}

interface RegistryFile {
  path: string;
  type: string;
  content: string;
}

interface RegistryItem {
  $schema: string;
  name: string;
  type: string;
  title: string;
  description: string;
  dependencies?: string[];
  registryDependencies?: string[];
  categories?: string[];
  files: RegistryFile[];
}

const ITEM_SCHEMA = "https://ui.shadcn.com/schema/registry-item.json";
const NOTE = "Generated by nudge-icons; changes are overwritten by `shadcn add --overwrite`.";

const itemUrl = (flavor: Flavor, name: string) =>
  [registryUrl, flavor.dir, `${name}.json`].filter(Boolean).join("/");

/** The shared core: factory, SVG rendering, types and the base motion CSS. */
function coreItem(flavor: Flavor): RegistryItem {
  const src = join(root, "packages", flavor.pkg, "src");
  const libFiles = readdirSync(join(src, "lib"))
    .filter((f) => /\.tsx?$/.test(f) && !/\.test\./.test(f))
    .sort();
  const files: RegistryFile[] = libFiles.map((f) => ({
    path: `${CORE_DIR}/${f}`,
    type: "registry:lib",
    // The core lives in one folder in the user's project, next to its base CSS.
    content: readFileSync(join(src, "lib", f), "utf8").replace(
      /(["'])\.\.\/generated\/base-css\1/g,
      '"./base-css"',
    ),
  }));
  files.push({
    path: `${CORE_DIR}/base-css.ts`,
    type: "registry:lib",
    content: readFileSync(join(src, "generated", "base-css.ts"), "utf8"),
  });
  return {
    $schema: ITEM_SCHEMA,
    name: CORE_ITEM,
    type: "registry:lib",
    title: `nudge-icons core (${flavor.label})`,
    description: `Shared code for nudge-icons ${flavor.label} components: the icon factory, SVG rendering, types and the base motion CSS. ${NOTE}`,
    ...(flavor.dependencies.length && { dependencies: flavor.dependencies }),
    files,
  };
}

function iconItem(
  flavor: Flavor,
  icon: IconListEntry,
  id: string,
  component: string,
): RegistryItem {
  const file = join(root, "packages", flavor.pkg, "src", "generated", "icons", `${id}.ts`);
  const content = readFileSync(file, "utf8")
    .replace(/^\/\/ Generated by .*\n/, `// ${component} from nudge-icons. ${NOTE}\n`)
    .replace(/(["'])\.\.\/\.\.\/lib\/([\w-]+)\1/g, `"@/${CORE_DIR}/$2"`);
  return {
    $schema: ITEM_SCHEMA,
    name: id,
    type: "registry:component",
    title: component,
    description: `Animated ${id.replace(/-/g, " ")} icon (${flavor.label}).`,
    registryDependencies: [itemUrl(flavor, CORE_ITEM)],
    ...(icon.category && { categories: [icon.category] }),
    files: [{ path: `${ICONS_DIR}/${id}.ts`, type: "registry:component", content }],
  };
}

/**
 * Copied files may import only the framework, the core through `@/${CORE_DIR}/…`, and
 * siblings inside the core. Anything else would break in the user's project.
 */
function checkImports(flavor: Flavor, items: RegistryItem[]) {
  const core = new Set(items[0]?.files.map((f) => basename(f.path).replace(/\.tsx?$/, "")) ?? []);
  const problems: string[] = [];
  for (const item of items) {
    for (const file of item.files) {
      for (const [, spec = ""] of file.content.matchAll(/\bfrom\s+["']([^"']+)["']/g)) {
        const inCore = item.name === CORE_ITEM && spec.startsWith("./") && core.has(spec.slice(2));
        const alias = `@/${CORE_DIR}/`;
        const viaAlias = spec.startsWith(alias) && core.has(spec.slice(alias.length));
        if (spec !== flavor.pkg && !inCore && !viaAlias) problems.push(`${file.path}: "${spec}"`);
      }
    }
  }
  if (problems.length) {
    throw new Error(
      `${flavor.label} registry files import what they cannot reach:\n${problems.join("\n")}`,
    );
  }
}

function write(file: string, data: unknown) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`);
}

const list = JSON.parse(
  readFileSync(join(root, "packages", "svg", "icons.json"), "utf8"),
) as IconListEntry[];

rmSync(out, { recursive: true, force: true });
let count = 0;
for (const flavor of FLAVORS) {
  const dir = join(out, flavor.dir);
  const items = [coreItem(flavor)];
  for (const icon of list) {
    for (const v of icon.variants) items.push(iconItem(flavor, icon, v.id, v.component));
  }
  checkImports(flavor, items);
  for (const item of items) write(join(dir, `${item.name}.json`), item);
  // Index in the shadcn registry format, without file contents.
  write(join(dir, "registry.json"), {
    $schema: "https://ui.shadcn.com/schema/registry.json",
    name: "nudge-icons",
    homepage: siteUrl,
    items: items.map((item) => {
      const { files, ...rest } = item;
      return {
        ...rest,
        $schema: undefined,
        files: files.map(({ path, type }) => ({ path, type })),
      };
    }),
  });
  count = items.length - 1;
}
console.log(
  `Registry: ${count} components and the core for ${FLAVORS.map((f) => f.label).join(" and ")} in ${relative(root, out)}/`,
);
